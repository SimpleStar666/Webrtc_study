// ============================================================================
// jitter_buffer.cpp - 抖动缓冲区实现
// ============================================================================
//
// 本文件实现了 JitterBuffer 类的核心逻辑，包括 RTP 包的插入、丢包检测、
// 重排序和消费输出。
//
// 【核心算法 - 序列号差值计算与回绕处理】
//
// RTP 序列号是 16 位无符号整数（0-65535），在比较序列号大小时必须正确
// 处理回绕（wraparound）问题。本实现使用的关键技巧是：
//
//   int16_t diff = static_cast<int16_t>(seq - expectedSeq);
//
// 原理：
//   当 seq 和 expectedSeq 都是 uint16_t 时，seq - expectedSeq 的结果
//   也是 uint16_t（模 65536 运算）。将这个结果强制转换为 int16_t 后，
//   由于二进制补码的表示方式：
//     - 值 0~32767 表示 seq >= expectedSeq（正常递增或相等）
//     - 值 32768~65535（即 int16_t 的 -32768~-1）表示 seq < expectedSeq（乱序/重复）
//
// 示例：
//   expectedSeq=100, seq=102 → diff=2   （正常，跳了2个包）
//   expectedSeq=65535, seq=0 → diff=1   （回绕，正常递增）
//   expectedSeq=65535, seq=2 → diff=3   （回绕，跳了3个包）
//   expectedSeq=100, seq=99  → diff=-1  （乱序，迟到的包）
//   expectedSeq=0, seq=65534 → diff=-2  （回绕方向的乱序）
//
// 【核心算法 - 丢包检测】
//
// 当收到的包的序列号大于期望序列号时，说明中间有包缺失：
//   diff = seq - expectedSeq
//   丢包数 = diff - 1
//
// 例如：期望 seq=100，收到 seq=103，则 diff=3，丢包数=2（seq 101, 102 丢失）
//
// 注意：这种估算可能不准确，因为"缺失"的包可能只是迟到了（乱序），
// 后续可能还会到达。但在实时通信中，通常将间隙视为丢包。
//
// 【核心算法 - consume 重排序输出】
//
// consume() 从缓冲区中取出可以安全输出的包，策略如下：
//   1. diff <= 0: 包已到或迟到，直接输出
//   2. diff <= 3: 间隙较小（1-3个包），判定为丢包，不再等待，直接输出
//   3. diff > 3:  间隙较大，可能包还在路上，跳过等待
//
// 阈值 3 的含义：如果连续缺失 3 个以上的包，很可能不是乱序而是真的丢包，
// 此时应该输出已有的包，避免延迟过大。
// ============================================================================

#include "media/rtp/jitter_buffer.h"
#include "utils/logger.h"

namespace crystal {

// ============================================================================
// 构造函数
// ============================================================================
JitterBuffer::JitterBuffer(uint32_t targetDelayMs)
    : targetDelayMs_(targetDelayMs) {}

// ============================================================================
// insert - 向缓冲区插入 RTP 包
// ============================================================================
//
// 【算法流程】
// 1. 递增接收计数器
// 2. 如果是第一个包，用其序列号初始化 expectedSeq_，插入后返回
// 3. 计算序列号差值 diff（有符号，正确处理回绕）
// 4. 根据 diff 的值进行不同处理：
//    - diff == 0: 收到期望的包，正常插入
//    - diff > 0:  收到未来的包，检测间隙并估算丢包数
//    - diff < 0:  收到迟到/重复的包，仅插入缓冲区
//
// 【关于重复包】
// 当 diff < 0 时，包可能是迟到的（之前被判定为丢包）或重复的。
// 无论如何，将其插入缓冲区（如果已存在则覆盖），consume 时会处理。
void JitterBuffer::insert(const RtpPacket& pkt) {
    receivedCount_++;

    // ========================================================================
    // 第一个包的特殊处理
    // 用其序列号初始化 expectedSeq_，这样后续的包可以与之比较
    // ========================================================================
    if (firstPacket_) {
        expectedSeq_ = pkt.sequenceNumber();
        firstPacket_ = false;
        buffer_[pkt.sequenceNumber()] = pkt;
        Logger::debug("JitterBuffer: first packet seq={}", pkt.sequenceNumber());
        return;
    }

    uint16_t seq = pkt.sequenceNumber();

    // ========================================================================
    // 计算序列号差值（有符号），正确处理回绕
    //
    // 关键: static_cast<int16_t> 将无符号差值转为有符号值
    // 例如: seq=0, expected=65535 → uint16_t差值=1 → int16_t差值=1（回绕正常）
    //       seq=99, expected=100   → uint16_t差值=65535 → int16_t差值=-1（乱序）
    // ========================================================================
    int16_t diff = static_cast<int16_t>(seq - expectedSeq_);

    if (diff == 0) {
        // ====================================================================
        // 收到期望的包（正常情况）
        // 直接插入缓冲区
        // ====================================================================
        buffer_[seq] = pkt;
    } else if (diff > 0) {
        // ====================================================================
        // 收到未来的包（seq > expectedSeq_）
        // 说明中间有包缺失，估算丢包数
        // ====================================================================
        if (diff > 1) {
            // diff > 1 表示有间隙，缺失的包数 = diff - 1
            // 例如: expected=100, seq=103, diff=3, 缺失 101, 102 共 2 个包
            lostCount_ += static_cast<uint64_t>(diff - 1);
            Logger::debug("JitterBuffer: gap detected, expected {} got {}, {} lost",
                          expectedSeq_, seq, diff - 1);
        }
        // diff == 1 表示紧邻的下一个包，没有丢包
        buffer_[seq] = pkt;
    } else {
        // ====================================================================
        // 收到迟到或重复的包（seq < expectedSeq_）
        // diff < 0 意味着这个包的序列号小于期望值
        //
        // 可能的原因：
        //   1. 包乱序到达（之前被误判为丢包，现在迟到了）
        //   2. 包重复（网络重复发送）
        //
        // 仍然插入缓冲区，consume 时会根据当前 expectedSeq_ 决定是否输出
        // 注意: 之前已经将间隙计为丢包，这里不做修正（简化处理）
        // ====================================================================
        Logger::debug("JitterBuffer: late/duplicate packet seq={}", seq);
    }
}

// ============================================================================
// consume - 从缓冲区消费可输出的 RTP 包
// ============================================================================
//
// 【算法流程】
// 遍历缓冲区（std::map 按序列号排序），对每个包计算其与 expectedSeq_ 的差值：
//
// 1. diff <= 0: 包的序列号 <= 期望序列号
//    - 说明这个包已经"到期"（可能是之前期望的包，或迟到的包）
//    - 直接输出，更新 expectedSeq_ = seq + 1
//
// 2. 0 < diff <= 3: 包的序列号略大于期望值，间隙在 1-3 个包以内
//    - 判定为丢包，不再等待缺失的包
//    - 更新 expectedSeq_ = seq（跳过缺失的包），然后输出
//    - expectedSeq_ = seq + 1
//
// 3. diff > 3: 间隙较大（缺失超过 3 个包）
//    - 可能这些包还在路上（网络延迟较大但未丢包）
//    - 跳过，等待后续 insert 后再处理
//
// 【关于 expectedSeq_ 的更新】
// 每输出一个包，expectedSeq_ 更新为 seq + 1，表示下一个期望的序列号。
// 如果跳过了缺失的包（diff > 0 的情况），expectedSeq_ 直接跳到当前包的
// 序列号之后，表示放弃等待缺失的包。
std::vector<RtpPacket> JitterBuffer::consume() {
    std::vector<RtpPacket> result;

    // 缓冲区为空，直接返回
    if (buffer_.empty()) return result;

    // 遍历缓冲区中的所有包（按序列号排序）
    auto it = buffer_.begin();
    while (it != buffer_.end()) {
        uint16_t seq = it->first;

        // 计算序列号差值（有符号，正确处理回绕）
        int16_t diff = static_cast<int16_t>(seq - expectedSeq_);

        if (diff <= 0) {
            // ==================================================================
            // 包已到期（序列号 <= 期望值）
            // 输出该包，更新期望序列号
            // ==================================================================
            result.push_back(it->second);
            expectedSeq_ = seq + 1;  // 期望下一个序列号
            it = buffer_.erase(it);  // 从缓冲区移除已输出的包
        } else if (diff <= 3) {
            // ==================================================================
            // 间隙较小（1-3个包），判定为丢包，不再等待
            // 跳过缺失的包，输出当前包
            // ==================================================================
            expectedSeq_ = seq;  // 跳到当前序列号
            result.push_back(it->second);
            expectedSeq_ = seq + 1;  // 期望下一个序列号
            it = buffer_.erase(it);  // 从缓冲区移除已输出的包
        } else {
            // ==================================================================
            // 间隙较大（>3个包），可能包还在路上
            // 跳过，等待后续包到达后再处理
            // ==================================================================
            ++it;
        }
    }

    return result;
}

// ============================================================================
// 统计方法实现
// ============================================================================

// 获取丢包总数
uint64_t JitterBuffer::lostPacketCount() const { return lostCount_; }

// 获取已接收包总数
uint64_t JitterBuffer::receivedPacketCount() const { return receivedCount_; }

// ============================================================================
// 计算丢包率
// ============================================================================
//
// 丢包率 = 丢包数 / (接收数 + 丢包数)
//
// 分母使用 receivedCount_ + lostCount_ 而非仅 receivedCount_ 的原因：
// 丢包率应该反映"应该收到的包中丢失的比例"，应该收到的包 = 实际收到的 + 丢失的
//
// 例如: 接收了 97 个包，检测到 3 个丢包
//   丢包率 = 3 / (97 + 3) = 3% （正确）
//   如果用 3 / 97 = 3.09% （略有偏差）
double JitterBuffer::lossRate() const {
    uint64_t total = receivedCount_ + lostCount_;
    if (total == 0) return 0.0;
    return static_cast<double>(lostCount_) / static_cast<double>(total);
}

} // namespace crystal
