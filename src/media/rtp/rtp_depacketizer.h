// ============================================================================
// rtp_depacketizer.h - RTP 解包器定义
// ============================================================================
//
// 本文件定义了 CrystalRTC 项目中的 RTP 解包器 RtpDepacketizer。
//
// 【在 WebRTC 系统中的角色】
// 解包器（Depacketizer）是打包器的逆操作，负责从接收到的 RTP 包中还原出
// 编码后的音视频数据帧。在接收端，RTP 包经过 Jitter Buffer 重排序后，
// 交给解包器处理，解包器将 RTP 负载中的数据重组为完整的编码帧。
//
// 【核心概念 - FU-A 重组】
// 对于 H.264 视频，解包器需要处理两种情况：
//
// 1. 单 NAL 单元包: RTP 负载直接就是一个完整的 NAL 单元，无需重组
//
// 2. FU-A 分片包: 一个 NAL 被分为多个 RTP 包传输，解包器需要：
//    a) 识别 FU-A 包（NAL type = 28）
//    b) 从 Start 包（S=1）开始收集数据
//    c) 将中间包的数据追加到缓冲区
//    d) 在 End 包（E=1）到达时完成重组，还原出完整的 NAL 单元
//
// 【FU-A 重组的状态机】
//
//   [空闲] --收到 Start 包--> [收集中] --收到中间包--> [收集中] --收到 End 包--> [空闲]
//                                         |                              |
//                                         +-- 收到新 Start 包 --> 丢弃旧数据，重新开始
//
// 【与 RFC 规范的对应】
// - H.264 解包: 遵循 RFC 6184 Section 5.8 (FU-A) 和 Section 5.6 (Single NAL)
// - Opus 解包:  遵循 RFC 7587，直接提取负载
// ============================================================================

#pragma once

#include "media/rtp/rtp_packet.h"
#include <cstdint>
#include <vector>

namespace crystal {

// ============================================================================
// RtpDepacketizer 类 - RTP 解包器
// ============================================================================
//
// 【职责】
// 从接收到的 RTP 包中还原出完整的编码帧数据。对于 H.264 视频，
// 需要处理 FU-A 分片的重组；对于 Opus 音频，直接提取负载即可。
//
// 【设计思路】
// 解包器是有状态的：它维护一个 FU-A 重组缓冲区 fuBuffer_ 和状态标志
// fuStarted_。当收到 FU-A Start 包时开始新的重组过程，中间包追加数据，
// End 包完成重组并输出完整的 NAL 单元。
//
// 这种有状态设计是必要的，因为 FU-A 分片可能跨越多个 RTP 包，
// 且这些包可能乱序到达（尽管 Jitter Buffer 已经做了重排序，
// 但仍需处理丢包导致的分片不完整情况）。
//
// 【容错处理】
// - 收到单 NAL 包时，如果正在重组 FU-A，则丢弃不完整的旧缓冲区
// - 收到新的 FU-A Start 包时，如果正在重组，则丢弃旧数据重新开始
// - 收到 FU-A 中间/结束包但没有 Start 包时，丢弃该包
// ============================================================================
class RtpDepacketizer {
public:
    RtpDepacketizer();

    // 从 RTP 包中解包 H.264 数据
    // 参数:
    //   pkt - 接收到的 RTP 包
    // 返回值:
    //   完整 NAL 单元的向量（可能为空，如 FU-A 中间包不产生输出；
    //   也可能包含 1 个 NAL，如单 NAL 包或 FU-A End 包完成重组时）
    // 核心逻辑:
    //   - NAL type 1-23: 单 NAL 单元，直接输出
    //   - NAL type 28:   FU-A 分片，按状态机重组
    //   - NAL type 24:   STAP-A（当前仅日志提示，未完全实现）
    std::vector<std::vector<uint8_t>> depacketizeH264(const RtpPacket& pkt);

    // 从 RTP 包中解包 Opus 数据
    // 参数:
    //   pkt - 接收到的 RTP 包
    // 返回值:
    //   包含单个 Opus 帧数据的向量（Opus 不需要重组，直接提取负载）
    std::vector<std::vector<uint8_t>> depacketizeOpus(const RtpPacket& pkt);

private:
    // ========================================================================
    // 成员变量 - FU-A 重组状态
    // ========================================================================

    // FU-A 重组缓冲区
    // 当收到 FU-A Start 包时，先写入重建的 NAL Header，然后追加分片数据
    // 当收到 FU-A End 包时，缓冲区中就是完整的 NAL 单元
    std::vector<uint8_t> fuBuffer_;

    // FU-A 重组状态标志
    // true  = 正在收集 FU-A 分片（已收到 Start 包，尚未收到 End 包）
    // false = 空闲状态，未在进行 FU-A 重组
    bool fuStarted_ = false;
};

} // namespace crystal
