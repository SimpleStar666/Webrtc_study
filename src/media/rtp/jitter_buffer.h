// ============================================================================
// jitter_buffer.h - 抖动缓冲区定义
// ============================================================================
//
// 本文件定义了 CrystalRTC 项目中的抖动缓冲区 JitterBuffer。
//
// 【在 WebRTC 系统中的角色】
// Jitter Buffer（抖动缓冲区）是 WebRTC 接收端的核心组件之一，位于网络层
// 和解码器之间。它的主要职责是：
//
// 1. 重新排序：UDP 传输不保证包的顺序到达，Jitter Buffer 根据序列号
//    将乱序的 RTP 包重新排列为正确的顺序
//
// 2. 吸收抖动：网络延迟的波动（jitter）会导致包到达间隔不均匀，
//    Jitter Buffer 通过引入可控的延迟来平滑这种波动
//
// 3. 丢包检测：通过检测序列号间隙来发现丢包事件
//
// 4. 丢包统计：记录丢包数量和丢包率，供 RTCP 报告和自适应码率使用
//
// 【核心概念 - 网络抖动（Jitter）】
// 网络抖动是指数据包到达时间的变化量。在理想网络中，每个 RTP 包的到达
// 间隔是固定的（如 20ms 一帧），但实际网络中，到达间隔可能在 5ms~50ms
// 之间波动。Jitter Buffer 通过引入一个目标延迟（targetDelay），将包
// 缓存一段时间后再输出，从而消除这种波动。
//
// 【核心概念 - 序列号回绕（Sequence Number Wraparound）】
// RTP 序列号为 16 位无符号整数（0-65535），每发送一个包递增 1。
// 当序列号从 65535 跳到 0 时，称为"回绕"（wraparound）。
//
// 处理回绕的关键技巧是将无符号差值转换为有符号差值：
//   int16_t diff = static_cast<int16_t>(seq_new - seq_expected);
//
// 例如：
//   expected=65534, seq=65535 → diff = 1（正常递增）
//   expected=65535, seq=0     → diff = 1（回绕，仍为正常递增）
//   expected=100,   seq=99    → diff = -1（乱序/重复）
//
// 这利用了 16 位无符号整数减法的溢出特性，以及 int16_t 的二进制补码
// 解释方式，使得回绕前后的差值计算自动正确。
//
// 【核心设计 - 两个序列号指针的分离】
// 本实现使用两个独立的序列号指针，分别服务于丢包检测和排序输出：
//
//   expectedSeq_    - 由 insert() 维护，用于丢包检测
//                     语义："下一个期望从网络收到的序列号"
//                     只在 insert() 中更新，consume() 只读不写
//
//   nextOutputSeq_  - 由 consume() 维护，用于排序输出
//                     语义："下一个期望从缓冲区输出的序列号"
//                     只在 consume() 中更新，insert() 不使用
//
// 为什么要分离？
//   如果共用一个变量，consume() 在输出迟到包时会"回退"序列号指针，
//   导致下一次 insert() 的丢包检测出错（重复计算已收到的包为丢包）。
//
//   例如（共用变量的错误场景）：
//     insert(100): expectedSeq_=101
//     insert(105): expectedSeq_=106, 丢包4个
//     consume():   输出100, expectedSeq_回退为101
//     insert(106): diff=106-101=5, 又多算5个丢包！← 错误
//
//   分离后：
//     insert(100): expectedSeq_=101
//     insert(105): expectedSeq_=106, 丢包4个
//     consume():   输出100, nextOutputSeq_=101（不影响expectedSeq_）
//     insert(106): diff=106-106=0, 无丢包 ← 正确
//
// 【数据结构选择 - std::map】
// 本实现使用 std::map<uint16_t, RtpPacket> 存储缓冲区中的 RTP 包，
// 选择 map 的原因：
//   1. 自动按序列号排序，便于按序输出
//   2. 支持高效的查找和删除
//   3. 能处理序列号不连续的情况（丢包导致的间隙）
//
// 注意：由于序列号回绕，map 的键值在回绕点附近不是严格递增的，
// 但在实际使用中，缓冲区中通常不会同时存在回绕前后的包，
// 所以 map 的排序特性仍然有效。
// ============================================================================

#pragma once

#include "media/rtp/rtp_packet.h"
#include <cstdint>
#include <map>
#include <vector>

namespace crystal {

// ============================================================================
// JitterBuffer 类 - 抖动缓冲区
// ============================================================================
//
// 【职责】
// 缓存接收到的 RTP 包，按序列号排序后输出，同时检测和统计丢包。
//
// 【设计思路】
// 本实现采用简化的 Jitter Buffer 设计：
//   - insert(): 将 RTP 包插入缓冲区，检测丢包
//   - consume(): 从缓冲区中取出可以输出的包
//
// 与生产级 Jitter Buffer（如 WebRTC 的 NetEq）相比，本实现：
//   - 不基于时间驱动（没有定时器或延迟计算）
//   - 不做自适应延迟调整
//   - 不做丢包隐藏（PLC）
//   - 使用简化的序列号间隙检测算法
//
// 【consume 算法思路】
// 遍历缓冲区中的包，按序列号顺序输出：
//   - diff <= 0: 包的序列号 <= 期望输出序列号，说明是已到或迟到的包，输出
//   - diff <= 3: 包的序列号略大于期望值，间隙较小（1-3个包），
//     可能是丢包，不再等待，直接输出
//   - diff > 3: 间隙较大，可能包还在路上，跳过等待
//
// 这个阈值 3 是一个经验值，在延迟和丢包容忍之间做权衡。
// ============================================================================
class JitterBuffer {
public:
    // 构造函数
    // 参数:
    //   targetDelayMs - 目标延迟（毫秒），默认 40ms
    //                   该值影响缓冲区等待多长时间后输出包
    //                   值越大，抗抖动能力越强，但延迟越高
    //                   典型值: 音频 20-60ms，视频 40-120ms
    explicit JitterBuffer(uint32_t targetDelayMs = 40);

    // 向缓冲区插入一个 RTP 包
    // 参数:
    //   pkt - 接收到的 RTP 包
    // 核心逻辑:
    //   1. 第一个包：初始化 expectedSeq_，直接插入
    //   2. diff == 0: 收到期望的包，正常插入
    //   3. diff > 0:  收到未来的包，检测间隙（丢包），插入
    //   4. diff < 0:  收到迟到/重复的包，仅插入（不重复计数）
    void insert(const RtpPacket& pkt);

    // 从缓冲区消费可输出的 RTP 包
    // 返回值:
    //   按序列号排序的 RTP 包向量
    // 核心逻辑:
    //   遍历缓冲区，输出序列号连续或间隙较小的包
    std::vector<RtpPacket> consume();

    // 获取丢包总数
    // 返回值: 检测到的丢包数量（基于序列号间隙估算）
    uint64_t lostPacketCount() const;

    // 获取已接收包总数
    // 返回值: 通过 insert() 插入的包数量
    uint64_t receivedPacketCount() const;

    // 获取丢包率
    // 返回值: 丢包率 = lostCount / (receivedCount + lostCount)，范围 [0.0, 1.0]
    double lossRate() const;

private:
    // ========================================================================
    // 成员变量
    // ========================================================================

    // 目标延迟（毫秒）
    // 影响 consume 的输出策略：延迟越大，等待更多包到达的概率越高
    uint32_t targetDelayMs_;

    // 缓冲区存储，使用 std::map 按序列号自动排序
    // key: RTP 序列号（16位，0-65535）
    // value: 对应的 RTP 包
    // 注意: map 中的键可能因序列号回绕而不连续，但通常缓冲区中
    // 不会同时存在回绕前后的包
    std::map<uint16_t, RtpPacket> buffer_;

    // ========================================================================
    // 两个独立的序列号指针（核心设计）
    // ========================================================================

    // 丢包检测指针 - 仅由 insert() 读写
    // 语义："下一个期望从网络收到的序列号"
    // 用于检测丢包和乱序：
    //   - 收到 seq == expectedSeq_: 正常，收到期望的包
    //   - 收到 seq > expectedSeq_: 有间隙，丢包数 = seq - expectedSeq_
    //   - 收到 seq < expectedSeq_: 迟到或重复
    // 每收到一个非迟到的包，expectedSeq_ 更新为 seq + 1
    // consume() 绝不修改此变量
    uint16_t expectedSeq_ = 0;

    // 排序输出指针 - 仅由 consume() 读写
    // 语义："下一个期望从缓冲区输出的序列号"
    // 用于判断缓冲区中的包是否可以输出：
    //   - seq <= nextOutputSeq_: 包已到期，可以输出
    //   - seq 略大于 nextOutputSeq_: 间隙小，判定丢包后输出
    //   - seq 远大于 nextOutputSeq_: 间隙大，等待
    // insert() 绝不修改此变量
    uint16_t nextOutputSeq_ = 0;

    // 是否为第一个包的标志
    // 第一个包到来时，同时初始化 expectedSeq_ 和 nextOutputSeq_
    bool firstPacket_ = true;

    // 丢包计数器
    // 当检测到序列号间隙时，间隙大小（diff）即为估算的丢包数
    // 例如: expectedSeq_=101, 收到 seq=103, diff=2, 丢包数=2（101,102缺失）
    uint64_t lostCount_ = 0;

    // 已接收包计数器
    // 每次 insert() 调用时递增
    uint64_t receivedCount_ = 0;
};

} // namespace crystal
