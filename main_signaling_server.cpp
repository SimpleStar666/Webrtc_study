// ============================================================================
// main_signaling_server.cpp - CrystalRTC 信令服务器入口
// ============================================================================
//
// 【程序用途】
//   本程序是 CrystalRTC 信令服务器的启动入口。信令服务器是 WebRTC 架构中
//   不可或缺的组件，负责在两个对等端之间转发 SDP Offer/Answer 和 ICE Candidate，
//   从而帮助双方建立 P2P 连接。
//
//   注意：信令服务器仅参与连接建立阶段，一旦 P2P 连接建立成功，
//   音视频数据直接在对等端之间传输，不再经过信令服务器。
//
// 【运行方式】
//   ./signaling_server
//   服务器默认监听 0.0.0.0:8765，无需命令行参数。
//
// 【信令服务器在 WebRTC 中的角色】
//
//   客户端A                信令服务器                客户端B
//     │                       │                       │
//     │── joinRoom ──────────>│<──────── joinRoom ────│
//     │                       │                       │
//     │<── peer_joined ───────│────── peer_joined ──>│
//     │                       │                       │
//     │── offer(SDP) ────────>│────── offer(SDP) ───>│
//     │                       │                       │
//     │<── answer(SDP) ───────│<───── answer(SDP) ───│
//     │                       │                       │
//     │── ICE Candidate ─────>│───── ICE Candidate ─>│
//     │<── ICE Candidate ─────│<──── ICE Candidate ──│
//     │                       │                       │
//     │═════════════ P2P 直连建立 ═══════════════════│
//     │<──────── 音视频数据直传 ───────────────────>│
//
// 【涉及的模块】
//   - SignalingServer (signaling_server.h) : 信令服务器核心实现
//     - WebSocket 服务器：接受客户端连接
//     - 房间管理：维护房间和成员列表
//     - 消息转发：在房间成员之间转发信令消息
//   - Logger (logger.h) : 日志系统
//
// ============================================================================

#include "signaling/signaling_server.h"
#include "utils/logger.h"

// ============================================================================
// 主函数：信令服务器入口
// ============================================================================
// 启动流程：
//   1. 初始化日志系统
//   2. 创建信令服务器实例，绑定地址和端口
//   3. 启动服务器，开始监听客户端连接
//   4. 服务器在后台运行，直到进程被终止
// ============================================================================
int main(int argc, char* argv[]) {
    // 初始化日志系统，标识为 "signaling_server"
    crystal::Logger::init("signaling_server");

    // 创建信令服务器实例
    // "0.0.0.0" 表示监听所有网络接口（允许外部客户端连接）
    // 8765 是默认端口号，客户端连接时需要使用相同端口
    crystal::SignalingServer server("0.0.0.0", 8765);

    // 启动服务器，开始监听 WebSocket 连接
    // 此调用会阻塞当前线程，服务器将持续运行直到进程被终止（如 Ctrl+C）
    server.start();

    return 0;
}
